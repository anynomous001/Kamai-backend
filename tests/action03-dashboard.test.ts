import { describe, it, expect, beforeAll, afterAll } from 'vitest';
import { buildApp } from '../src/app.js';
import { prisma } from '../src/shared/database/prisma.js';

describe('Action 3 E2E: Summary Dashboard', () => {
  let app: any;

  beforeAll(async () => {
    app = await buildApp();
    // Setup the mock bypass baker
    await prisma.baker.deleteMany({ where: { id: 'test-baker-id' } });
    await prisma.baker.create({
      data: {
        id: 'test-baker-id',
        phoneNumber: '+919999999999',
        businessName: 'Test Bakery',
        ownerName: 'Test Owner',
        status: 'ACTIVE',
        subscriptionStatus: 'ACTIVE',
      }
    });
  });

  afterAll(async () => {
    await prisma.baker.deleteMany({
      where: { id: 'test-baker-id' },
    });
  });

  it('should return 200 and return structured dashboard summary statistics', async () => {
    const response = await app.inject({
      method: 'GET',
      url: '/api/dashboard/summary',
    });

    expect(response.statusCode).toBe(200);
    const body = JSON.parse(response.body);
    expect(body.success).toBe(true);
    expect(body.data.activeOrders).toBeDefined();
    expect(body.data.totalRevenue).toBeDefined();
  });
});
